#!/usr/bin/env node
'use strict';
/* Embed Supabase's root certificate so store.js can verify TLS.
 *
 *   node scripts/embed-supabase-ca.js prod-ca-2021.crt
 *
 * Get the file from: Supabase dashboard -> Project Settings -> Database ->
 * SSL Configuration -> Download certificate. It is a PUBLIC CA certificate, so
 * the module this writes is committed; the downloaded .crt can then be deleted.
 *
 * The certificate is embedded as a string in a JS module rather than read from
 * disk at runtime, so the function bundler cannot leave it behind.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const OUT = path.resolve(__dirname, '../netlify/functions/lib/supabase-ca.js');

function fail(msg) {
  console.error(`FAIL: ${msg}`);
  process.exit(1);
}

const file = process.argv[2];
if (!file) fail('give the downloaded certificate: node scripts/embed-supabase-ca.js <file.crt>');
if (!fs.existsSync(file)) fail(`no such file: ${file}`);

const blocks = fs.readFileSync(file, 'utf8')
  .match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g);
if (!blocks || blocks.length !== 1) {
  fail(`expected exactly one PEM certificate in ${file}, found ${blocks ? blocks.length : 0}`);
}
const pem = blocks[0].replace(/\r\n/g, '\n');

let cert;
try { cert = new crypto.X509Certificate(pem); }
catch (e) { fail(`not a readable certificate: ${e.message}`); }

if (!cert.ca) fail('this is not a CA certificate - download it from Database -> SSL Configuration');
if (new Date(cert.validTo) <= new Date()) fail(`this certificate expired on ${cert.validTo}`);
if (!/supabase/i.test(cert.subject)) {
  fail(`subject does not mention Supabase:\n  ${cert.subject.replace(/\n/g, ', ')}\nStop and check where this file came from.`);
}

const oneLine = s => s.replace(/\n/g, ', ');
const header = [
  "'use strict';",
  '/* Supabase root CA certificate - PUBLIC, safe to commit.',
  ' *',
  ' * Generated by scripts/embed-supabase-ca.js from the certificate downloaded at',
  ' * Supabase -> Project Settings -> Database -> SSL Configuration. Do not edit;',
  ' * re-run the script with a fresh download instead.',
  ' *',
  ` *   subject: ${oneLine(cert.subject)}`,
  ` *   valid:   ${cert.validFrom} -> ${cert.validTo}`,
  ` *   sha256:  ${cert.fingerprint256}`,
  ' */'
].join('\n');

fs.writeFileSync(OUT, `${header}\nmodule.exports = ${JSON.stringify(pem + '\n')};\n`);

console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
console.log(`  subject:     ${oneLine(cert.subject)}`);
console.log(`  issuer:      ${oneLine(cert.issuer)}`);
console.log(`  self-signed: ${cert.checkIssued(cert) ? 'yes (a root)' : 'no (an intermediate)'}`);
console.log(`  valid:       ${cert.validFrom} -> ${cert.validTo}`);
console.log(`  sha256:      ${cert.fingerprint256}`);
console.log(`\nYou can now delete ${file}.`);
